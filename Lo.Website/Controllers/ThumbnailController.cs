/// <summary>
/// /Game/Tools/ThumbnailAsset.ashx
///
/// Old-style thumbnail endpoint used by Lua scripts inside the game
/// server. The 2018M Lua calls this with parameters:
///   fmt — image format (png, jpg, gif)
///   wd  — width
///   ht  — height
///   aid — asset id
///
/// Returns the thumbnail image bytes. In real Roblox this would
/// dispatch a thumbnail render via RCC's ThumbnailGenerator. For a
/// 2018M revival we either:
///   (a) pre-render thumbnails when assets are uploaded (the
///       "store and serve" model used by most revivals)
///   (b) dispatch a render job to RCC and return a placeholder while it runs
///
/// We implement (a) here. See Finobe's luascripts/thumbnails/AvatarScript.lua
/// for the (b) approach.
///
/// Source: wiki/api-docs.md.
/// </summary>
public static class ThumbnailController
{
    public static void Map(RouteGroupBuilder g)
    {
        g.MapGet("/Game/Tools/ThumbnailAsset.ashx", Thumbnail);
    }

    private static async Task<IResult> Thumbnail(HttpContext ctx, AppDb db)
    {
        var fmt = (ctx.Request.Query["fmt"].ToString() ?? "png").ToLowerInvariant();
        var wd  = (int)0; int.TryParse(ctx.Request.Query["wd"], out wd);
        var ht  = (int)0; int.TryParse(ctx.Request.Query["ht"], out ht);
        var aid = (long)0; long.TryParse(ctx.Request.Query["aid"], out aid);
        if (wd == 0) wd = 420;
        if (ht == 0) ht = 420;

        if (aid <= 0) return Results.Bytes(Placeholder(fmt, wd, ht), MimeFor(fmt));

        var asset = await db.FindAssetAsync(aid);
        if (asset is null) return Results.Bytes(Placeholder(fmt, wd, ht), MimeFor(fmt));

        // Look for a pre-rendered thumbnail in storage\rbx\files\thumbs\
        var thumbDir = Path.Combine(@"C:\lo\storage\rbx\files\thumbs", asset.ThumbHash ?? $"asset_{aid}");
        var candidates = new[] { $"{aid}.{fmt}", $"{aid}.png" };
        foreach (var name in candidates)
        {
            var p = Path.Combine(thumbDir, name);
            if (File.Exists(p))
            {
                return Results.Bytes(File.ReadAllBytes(p), MimeFor(fmt));
            }
        }
        return Results.Bytes(Placeholder(fmt, wd, ht), MimeFor(fmt));
    }

    private static string MimeFor(string fmt) => fmt switch
    {
        "jpg" or "jpeg" => "image/jpeg",
        "gif"           => "image/gif",
        _               => "image/png"
    };

