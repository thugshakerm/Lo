@bot.tree.error
async def on_app_command_error(
    interaction: discord.Interaction, error: app_commands.AppCommandError
):
    if isinstance(error, app_commands.CommandInvokeError):
        error = error.original
    if isinstance(error, (madxka.MadxkaError, discord.HTTPException)):
        return  # already handled (or nothing to do)
    log.exception("unhandled app command error", exc_info=error)
    message = "🤔 something went wrong on my end. try again in a bit."
    if interaction.response.is_done():
        await interaction.followup.send(message, ephemeral=True)
    else:
        await interaction.response.send_message(message, ephemeral=True)


@bot.event
async def setup_hook():
    if GUILD_ID:
        await bot.tree.sync(guild=discord.Object(id=int(GUILD_ID)))
        log.info("commands synced to guild %s (instant)", GUILD_ID)
    else:
        await bot.tree.sync()
        log.info("global commands synced (may take a few minutes to show up)")


@bot.event
async def on_ready():
    log.info("logged in as %s (id=%s)", bot.user, bot.user.id)
    log.info("madxka base url: %s", BASE_URL)
    log.info("commands: %s", ", ".join(c.name for c in bot.tree.get_commands()))


async def main():
    session = aiohttp.ClientSession()
    try:
        bot.client = madxka.MadxkaClient(BASE_URL, session=session)
        await bot.start(TOKEN)
    finally:
        await bot.close()
        await session.close()


if __name__ == "__main__":
    import asyncio

    asyncio.run(main())
