def fmt_num(value) -> str:
    try:
        return f"{int(value):,}"
    except (TypeError, ValueError):
        return "0"


def fmt_dt(value) -> str:
    parsed = madxka.parse_datetime(value)
    if parsed is None:
        return "unknown"
    return discord.utils.format_dt(parsed)


def base_embed(title: str) -> discord.Embed:
    embed = discord.Embed(
        title=title[:256],
        color=EMBED_COLOR,
        timestamp=discord.utils.utcnow(),
    )
    embed.set_footer(text=FOOTER_TEXT)
    return embed


def error_embed(message: str) -> discord.Embed:
    embed = discord.Embed(description=message[:1024], color=ERROR_COLOR)
    embed.set_footer(text="MadXka lookup failed")
    return embed


# simple per-user cooldown so the madxka api isn't hammered
_cooldowns: dict[int, float] = {}


def on_cooldown(user_id: int) -> bool:
    now = time.monotonic()
    last = _cooldowns.get(user_id, 0.0)
    if now - last < COOLDOWN_SECONDS:
        return True
    _cooldowns[user_id] = now
    if len(_cooldowns) > 50_000:  # safety prune
        _cooldowns.clear()
    return False


def truncate(text: str, limit: int = 1024) -> str:
    text = (text or "").strip()
    if len(text) <= limit:
        return text or "No description."
    return text[: limit - 1].rstrip() + "…"


def badge_flags(user: dict) -> tuple[bool, bool]:
    verified = bool(user.get("isVerified"))
    staff = any(bool(user.get(key)) for key in STAFF_FIELDS)
    return verified, staff


def apply_badges(embed: discord.Embed, user: dict) -> list[discord.File]:
    """Attach the user's badge(s); returns the message files to send.

    one badge -> shown in the author row, right next to the username
    both      -> the two original badges as two separate images, side by side
    """
    verified, staff = badge_flags(user)
    if not verified and not staff:
        return []
    if verified != staff:  # exactly one of the two
        url = VERIFIED_BADGE_URL if verified else ADMIN_BADGE_URL
        name = str(user.get("name") or user.get("displayName") or "")[:128]
        embed.set_author(name=name, icon_url=url)
        return []
    # both: no author icon — send the two originals as separate attachments
    return [
        discord.File(VERIFIED_BADGE_FILE, filename="verified.png"),
        discord.File(ADMIN_BADGE_FILE, filename="admin.png"),
    ]


async def resolve_user(client: madxka.MadxkaClient, query: str) -> dict | None:
    """Resolve a username or numeric user id to the full user info dict."""
    query = query.strip()
    if query.isdigit():
        return await client.get_user(int(query))
    entry = await client.get_user_by_username(query)
    if not entry or not entry.get("id"):
        return None
    info = await client.get_user(int(entry["id"]))
    # fall back to the username lookup entry if the detail call 404s
    if not info:
        return {"id": entry["id"], "name": entry.get("name"),
                "displayName": entry.get("displayName")}
    return info


