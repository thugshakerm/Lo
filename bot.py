async def build_user_embed(client, query: str) -> discord.Embed | None:
    user = await resolve_user(client, query)
    if not user or not user.get("id"):
        return None
    user_id = int(user["id"])
    name = user.get("displayName") or user.get("name") or query

    headshots = await client.get_user_headshots([user_id])
    status_text = await client.get_user_status_text(user_id)

    embed = base_embed(f"👤 {name}")
    embed.url = f"{BASE_URL}/users/{user_id}"
    badge_files = apply_badges(embed, user)
    headshot = headshots.get(user_id)
    if headshot:
        embed.set_thumbnail(url=headshot)

    embed.add_field(name="Username", value=f"`{user.get('name') or query}`", inline=True)
    embed.add_field(name="User ID", value=f"`{user_id}`", inline=True)
    embed.add_field(name="Joined", value=fmt_dt(user.get("created")), inline=True)
    embed.add_field(name="Verified", value="✅" if user.get("isVerified") else "❌", inline=True)
    if user.get("totalrap") is not None:
        embed.add_field(name="RAP", value=f"💎 {fmt_num(user['totalrap'])}", inline=True)
    embed.add_field(
        name="Status",
        value="🔨 Banned" if user.get("isBanned") else "✅ Active",
        inline=True,
    )
    if status_text:
        embed.add_field(name="Status message", value=truncate(status_text, 1024), inline=False)
    embed.add_field(name="About", value=truncate(user.get("description")), inline=False)
    return embed, badge_files


async def build_item_embed(client, query: str) -> discord.Embed | None:
    query = query.strip()
    others: list[dict] = []
    if query.isdigit():
        details = await client.get_item_details([int(query)])
        if not details:
            return None
        item = details[0]
    else:
        results = await client.search_items(query, limit=6)
        if not results:
            return None
        ids = [int(r["id"]) for r in results if r.get("id") is not None]
        details = await client.get_item_details(ids)
        if not details:
            return None
        by_id = {int(d["id"]): d for d in details}
        item = by_id.get(int(results[0]["id"])) or details[0]
        for r in results[1:]:
            if r.get("id") is not None and int(r["id"]) in by_id:
                others.append(by_id[int(r["id"])])

    asset_id = int(item["id"])
    name = item.get("name") or f"Item {asset_id}"
    type_name = madxka.ASSET_TYPES.get(item.get("assetType"), "Unknown")
    emoji = TYPE_EMOJI.get(type_name, "📦")

    thumbs = await client.get_item_thumbnails([asset_id])
    thumb = thumbs.get(asset_id)

    embed = base_embed(f"{emoji} {name}")
    embed.url = f"{BASE_URL}/catalog/{asset_id}"
    if thumb:
        embed.set_thumbnail(url=thumb)

    price = item.get("price")
    if item.get("isForSale"):
        price_value = f"R${fmt_num(price)}" if price else "Free"
    else:
        price_value = "Not for sale"

    embed.add_field(name="Asset ID", value=f"`{asset_id}`", inline=True)
    embed.add_field(name="Type", value=type_name, inline=True)
    embed.add_field(name="Creator", value=str(item.get("creatorName") or "unknown"), inline=True)
    embed.add_field(name="Price", value=price_value, inline=True)
    if item.get("favoriteCount") is not None:
        embed.add_field(name="Favorites", value=f"⭐ {fmt_num(item['favoriteCount'])}", inline=True)
    if item.get("saleCount") is not None:
        embed.add_field(name="Sales", value=f"💰 {fmt_num(item['saleCount'])}", inline=True)

    restrictions = item.get("itemRestrictions") or []
    is_limited = any(r in ("Limited", "LimitedUnique") for r in restrictions)
    if is_limited:
        limited_value = "🔥 LimitedUnique" if "LimitedUnique" in restrictions else "🔥 Limited"
        units = item.get("unitsAvailableForConsumption")
        serials = item.get("serialCount")
        if units is not None:
            limited_value += f"\n{fmt_num(units)} left"
        elif serials:
            limited_value += f"\nof {fmt_num(serials)} serials"
        embed.add_field(name="Limited", value=limited_value, inline=True)
        if item.get("lowestPrice") is not None:
            embed.add_field(name="Lowest price", value=f"R${fmt_num(item['lowestPrice'])}", inline=True)

    embed.add_field(name="Created", value=fmt_dt(item.get("createdAt")), inline=True)
    embed.add_field(name="Updated", value=fmt_dt(item.get("updatedAt")), inline=True)
    if item.get("is18Plus"):
        embed.add_field(name="Age", value="⚠️ 18+", inline=True)

    embed.add_field(name="Description", value=truncate(item.get("description")), inline=False)
    if others:
        lines = [f"`{int(o['id'])}` {o.get('name') or 'item'}" for o in others[:4]]
        embed.add_field(name="More results", value="\n".join(lines), inline=False)
    return embed, []


async def build_game_embed(client, query: str) -> discord.Embed | None:
    query = query.strip()
    player_count = None

    if query.isdigit():
        candidate = int(query)
        universe_id = None
        place_id = None
        games = await client.get_games([candidate])
        if games:
            universe_id = int(games[0]["id"])
        else:
            places = await client.get_place_details([candidate])
            if places:
                universe_id = int(places[0]["universeId"])
                place_id = candidate
        if universe_id is None:
            return None
    else:
        results = await client.search_games(query, max_rows=6)
        if not results:
            return None
        top = results[0]
        universe_id = int(top["universeId"])
        place_id = top.get("placeId") or None
        player_count = top.get("playerCount")

    games = await client.get_games([universe_id])
    if not games:
        return None
    game = games[0]
    place_id = place_id or game.get("rootPlaceId")

    icons = await client.get_game_icons([universe_id])
    votes = await client.get_game_votes([universe_id])

    name = game.get("name") or f"Game {universe_id}"
    embed = base_embed(f"🎮 {name}")
    embed.url = f"{BASE_URL}/games/{place_id}"
    icon = icons.get(universe_id)
    if icon:
        embed.set_thumbnail(url=icon)

    embed.add_field(name="Universe ID", value=f"`{universe_id}`", inline=True)
    embed.add_field(name="Place ID", value=f"`{place_id}`" if place_id else "unknown", inline=True)
    creator = game.get("creator") or {}
    embed.add_field(
        name="Creator",
        value=str(creator.get("name") or "unknown"),
        inline=True,
    )
    if player_count is not None:
        embed.add_field(name="Players", value=f"👥 {fmt_num(player_count)}", inline=True)
    if game.get("visits") is not None:
        embed.add_field(name="Visits", value=f"👣 {fmt_num(game['visits'])}", inline=True)
    if game.get("favoritedCount") is not None:
        embed.add_field(name="Favorites", value=f"⭐ {fmt_num(game['favoritedCount'])}", inline=True)

    vote = votes.get(universe_id)
    if vote:
        up, down = int(vote.get("upVotes") or 0), int(vote.get("downVotes") or 0)
        total = up + down
        pct = f"{(up / total) * 100:.0f}%" if total else "n/a"
        embed.add_field(name="Votes", value=f"👍 {fmt_num(up)} / 👎 {fmt_num(down)} • {pct}")

    embed.add_field(name="Genre", value=madxka.genre_name(game.get("genre")), inline=True)
    if game.get("maxPlayers"):
        embed.add_field(name="Max players", value=f"👥 {fmt_num(game['maxPlayers'])}", inline=True)
    if game.get("price"):
        embed.add_field(name="Price", value=f"R${fmt_num(game['price'])}", inline=True)
    if game.get("year"):
        embed.add_field(name="Year", value=str(game["year"]), inline=True)
    embed.add_field(name="Created", value=fmt_dt(game.get("created")), inline=True)
    embed.add_field(name="Updated", value=fmt_dt(game.get("updated")), inline=True)
    embed.add_field(name="Description", value=truncate(game.get("description")), inline=False)
    return embed, []


async def build_avatar_embed(client, query: str) -> discord.Embed | None:
    user = await resolve_user(client, query)
    if not user or not user.get("id"):
        return None
    user_id = int(user["id"])
    name = user.get("displayName") or user.get("name") or query

    avatars = await client.get_user_full_avatars([user_id])
    headshots = await client.get_user_headshots([user_id])
    full_body = avatars.get(user_id)
    headshot = headshots.get(user_id)
    if not full_body and not headshot:
        return None

    embed = base_embed(f"🖼️ {name}'s Avatar")
    embed.url = f"{BASE_URL}/users/{user_id}"
    badge_files = apply_badges(embed, user)
    embed.set_image(url=full_body or headshot)
    if full_body and headshot:
        embed.set_thumbnail(url=headshot)

    embed.add_field(name="Username", value=f"`{user.get('name') or query}`", inline=True)
    embed.add_field(name="User ID", value=f"`{user_id}`", inline=True)
    embed.add_field(name="Joined", value=fmt_dt(user.get("created")), inline=True)
    return embed, badge_files


