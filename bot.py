async def run_lookup(interaction: discord.Interaction, builder):
    """Shared defer -> build embed -> edit flow with friendly errors."""
    user_id = interaction.user.id
    if on_cooldown(user_id):
        await interaction.response.send_message(
            "⏳ slow down! try again in a few seconds.", ephemeral=True
        )
        return
    await interaction.response.defer()
    try:
        result = await builder()
        if result is None:
            embed = error_embed(
                "😕 **Not found** — I couldn't find that on MadXka. "
                "Double-check the name/ID and try again."
            )
            files = []
        else:
            embed, files = result
        await interaction.edit_original_response(embed=embed, files=files or None)
    except madxka.MadxkaError as exc:
        await interaction.edit_original_response(embed=error_embed(f"⚠️ {exc}"))
    except discord.HTTPException:
        log.exception("discord HTTP error in run_lookup")


